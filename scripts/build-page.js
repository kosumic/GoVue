import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { MEDIA_BRIDGE } from '../src/youtube/mediaBridge.js';
const pageBridge = await build({ entryPoints: ['src/youtube/pageBridge.js'], bundle: true,
  platform: 'browser', format: 'iife', target: 'es2020', minify: true, write: false });
mkdirSync('src/youtube/generated', { recursive: true });
writeFileSync('src/youtube/generated/pageBridge.js',
  `// Generated by npm run page:build.\nexport const YOUTUBE_BRIDGE = ${JSON.stringify(pageBridge.outputFiles[0].text + '\ntrue;')};\n`);
const captionBridge = await build({ entryPoints: ['src/youtube/captionBridge.js'], bundle: true,
  platform: 'browser', format: 'iife', target: 'es2020', minify: true, write: false });
writeFileSync('src/youtube/generated/captionBridge.js',
  `// Generated by npm run page:build.\nexport const CAPTION_BRIDGE = ${JSON.stringify(captionBridge.outputFiles[0].text + '\ntrue;')};\n`);
const tokenRuntime = await build({ entryPoints: ['scripts/token-runtime.js'], bundle: true,
  platform: 'browser', format: 'iife', target: 'es2020', minify: true, write: false });
const tokenSource = '/* BgUtils (MIT)\n' + readFileSync('node_modules/bgutils-js/LICENSE', 'utf8') + '\n*/\n' + tokenRuntime.outputFiles[0].text;
writeFileSync('src/youtube/generated/tokenRuntime.js',
  `// Generated by npm run page:build.\nexport const TOKEN_RUNTIME = ${JSON.stringify(tokenSource)};\n`);
writeFileSync('src/youtube/generated/nativeShellTokenRuntime.js', tokenSource);
const scripts = [
  'core',
  'ui',
  'nav',
  'download',
  'display_dislikes',
  'hide_shorts',
  'gallery',
  'player-hook',
  'shorts',
  'shorts-quality',
  'remove_shorts_ads',
]
  .map((name) => readFileSync(`src/youtube/litube/${name}.js`, 'utf8'))
  .join('\n;\n');
const extension = readFileSync('src/youtube/litube/extension.js', 'utf8');
const browser = `/* Adapted from LiTube, GPL-3.0. See notices/LiTube-GPL-3.0.txt. */\nif(location.protocol==='https:'&&['www.youtube.com','m.youtube.com','youtube.com','music.youtube.com'].includes(location.hostname)){\n${readFileSync('scripts/browser-adapter.js', 'utf8')}\n${scripts}\n;Lite.module('extensions',()=>{${extension};return true;});\n}\ntrue;`;
writeFileSync(
  'src/youtube/generated/browserBridge.js',
  `// Generated by npm run page:build.\nexport const BROWSER_BRIDGE = ${JSON.stringify(browser)};\n`,
);
const bootstrap = `if(location.protocol==='https:'&&['www.youtube.com','m.youtube.com','youtube.com','music.youtube.com'].includes(location.hostname)){${readFileSync('src/youtube/litube/remove_shorts_ads.js', 'utf8')}}true;`;
writeFileSync(
  'src/youtube/generated/browserBootstrap.js',
  `// Generated by npm run page:build.\nexport const BROWSER_BOOTSTRAP = ${JSON.stringify(bootstrap)};\n`,
);
writeFileSync('src/youtube/generated/nativeShellBootstrap.js', `${bootstrap}\n${MEDIA_BRIDGE}`);
writeFileSync('src/youtube/generated/nativeShellBrowser.js', `${pageBridge.outputFiles[0].text}\n${MEDIA_BRIDGE}\n${browser}`);
