import { build } from 'esbuild';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
const result = await build({
  entryPoints: ['scripts/player-decoder.js'],
  bundle: true,
  platform: 'browser',
  format: 'iife',
  target: 'es2020',
  minify: true,
  legalComments: 'inline',
  write: false,
});
mkdirSync('src/youtube/generated', { recursive: true });
const license =
  readFileSync('node_modules/youtubei.js/LICENSE', 'utf8') +
  '\n\nBgUtils (MIT)\n' +
  readFileSync('node_modules/bgutils-js/LICENSE', 'utf8');
const source = `/* YouTube.js (MIT)\n${license}\n*/\nif (!window.__lingoplayDecode && location.protocol === 'https:' && ['www.youtube.com','m.youtube.com','youtube.com','music.youtube.com'].includes(location.hostname)) {\n${result.outputFiles[0].text}\n}\ntrue;`;
writeFileSync(
  'src/youtube/generated/playerDecoder.js',
  `// Generated by npm run page:build.\nexport const PLAYER_DECODER = ${JSON.stringify(source)};\n`,
);
const scripts = [
  'core',
  'ui',
  'nav',
  'download',
  'display_dislikes',
  'hide_shorts',
  'gallery',
  'player-hook',
  'shorts',
  'shorts-quality',
  'remove_shorts_ads',
]
  .map((name) => readFileSync(`src/youtube/litube/${name}.js`, 'utf8'))
  .join('\n;\n');
const extension = readFileSync('src/youtube/litube/extension.js', 'utf8');
const browser = `/* Adapted from LiTube, GPL-3.0. See notices/LiTube-GPL-3.0.txt. */\nif(location.protocol==='https:'&&['www.youtube.com','m.youtube.com','youtube.com','music.youtube.com'].includes(location.hostname)){\n${readFileSync('scripts/browser-adapter.js', 'utf8')}\n${scripts}\n;Lite.module('extensions',()=>{${extension};return true;});\n}\ntrue;`;
writeFileSync(
  'src/youtube/generated/browserBridge.js',
  `// Generated by npm run page:build.\nexport const BROWSER_BRIDGE = ${JSON.stringify(browser)};\n`,
);
const bootstrap = `if(location.protocol==='https:'&&['www.youtube.com','m.youtube.com','youtube.com','music.youtube.com'].includes(location.hostname)){${readFileSync('src/youtube/litube/remove_shorts_ads.js', 'utf8')}}true;`;
writeFileSync(
  'src/youtube/generated/browserBootstrap.js',
  `// Generated by npm run page:build.\nexport const BROWSER_BOOTSTRAP = ${JSON.stringify(bootstrap)};\n`,
);
